/**
 * Returns variants for a given model (chassis code)
 * @param {string} chassisCode
 */
export function getVariantsForModel(chassisCode) {
  if (!chassisCode) return [];
  const found = BMW_MODELS.find(m => m.chassisCode?.toLowerCase() === chassisCode.toLowerCase());
  return found ? found.variants : [];
}

